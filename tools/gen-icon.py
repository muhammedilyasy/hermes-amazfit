"""Pixel-art logo: a black starburst ("spark") on a 18 x 18 grid, drawn crisp with
nearest-neighbour scaling.
  assets/default.s/icon.png   248 px app icon, white disc
  assets/default.s/logo.png   44 px white tile with the spark, for the in-app header
  setting/logo.js             the same tile as a base64 PNG for the phone Settings App
  tools/icon-512.png          large copy for review
Usage: python3 tools/gen-icon.py
"""
import base64
import io
import math
import os
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
G = 18  # grid size
INK = (31, 30, 29, 255)

# Eight rays, two pixels wide, with uneven lengths (in cells from the centre) so the
# spark feels hand-drawn rather than mechanical.
RAYS = [(-90, 8.8), (-45, 8.6), (0, 7.6), (45, 7.4), (90, 8.4), (135, 8.8), (180, 8.0), (225, 6.8)]
HUB = 2.1  # radius of the solid centre, in cells


def spark_grid():
    c = G / 2  # even grid: the centre is a pixel corner, so straight rays are exactly 2 px
    on = set()
    for x in range(G):
        for y in range(G):
            dx, dy = x + 0.5 - c, y + 0.5 - c
            if math.hypot(dx, dy) <= HUB:
                on.add((x, y))
                continue
            for ang, length in RAYS:
                a = math.radians(ang)
                t = dx * math.cos(a) + dy * math.sin(a)  # along the ray
                perp = abs(-dx * math.sin(a) + dy * math.cos(a))  # across it
                # Diagonals get a narrower band, which snaps to a clean 2 px staircase.
                width = 1.0 if ang % 90 == 0 else 0.72
                if 0 < t <= length and perp <= width:
                    on.add((x, y))
                    break
    return on


def draw(cell, bg=None, disc=False, pad=0):
    on = spark_grid()
    size = G * cell + pad * 2
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    px = img.load()
    if bg:
        for x in range(size):
            for y in range(size):
                inside = not disc or math.hypot(x + 0.5 - size / 2, y + 0.5 - size / 2) <= size / 2
                if inside:
                    px[x, y] = bg
    for gx, gy in on:
        for x in range(pad + gx * cell, pad + (gx + 1) * cell):
            for y in range(pad + gy * cell, pad + (gy + 1) * cell):
                px[x, y] = INK
    return img


def tile(cell, pad, radius):
    spark = draw(cell)
    size = spark.width + pad * 2
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    ImageDraw.Draw(img).rounded_rectangle((0, 0, size - 1, size - 1), radius=radius, fill=(255, 255, 255, 255))
    img.alpha_composite(spark, (pad, pad))
    return img


def main():
    # App icon: white disc, spark at ~65% of the width.
    cell = 9
    icon = draw(cell, bg=(255, 255, 255, 255), disc=True, pad=(248 - G * cell) // 2)
    icon = icon.resize((248, 248), Image.NEAREST)
    icon.save(os.path.join(ROOT, "assets", "default.s", "icon.png"))
    icon.resize((512, 512), Image.NEAREST).save(os.path.join(ROOT, "tools", "icon-512.png"))
    # Header / settings tile: white rounded square, spark inset.
    tile(2, 4, 10).save(os.path.join(ROOT, "assets", "default.s", "logo.png"))
    buf = io.BytesIO()
    tile(4, 12, 22).save(buf, format="PNG")
    b64 = base64.b64encode(buf.getvalue()).decode()
    with open(os.path.join(ROOT, "setting", "logo.js"), "w") as f:
        f.write("// Generated by tools/gen-icon.py: the pixel spark tile as a base64 PNG.\n")
        f.write("export const LOGO = 'data:image/png;base64," + b64 + "'\n")
    print("wrote icon.png, logo.png, setting/logo.js")


if __name__ == "__main__":
    main()
